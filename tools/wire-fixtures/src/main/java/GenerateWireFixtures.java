import com.google.protobuf.CodedOutputStream;
import java.io.ByteArrayOutputStream;
import java.util.LinkedHashSet;
import java.util.Random;
import java.util.Set;

/** Generates the shared fixtures using Google's runtime, in an isolated JVM.
 * Invoked by the sbt generateWireFixtures task with the pinned runtime version.
 */
public final class GenerateWireFixtures {
  private static void emit(String kind, long value) throws Exception {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    CodedOutputStream out = CodedOutputStream.newInstance(bytes);
    switch (kind) {
      case "int32": out.writeInt32NoTag((int) value); break;
      case "uint32": out.writeUInt32NoTag((int) value); break;
      case "sint32": out.writeSInt32NoTag((int) value); break;
      case "fixed32": out.writeFixed32NoTag((int) value); break;
      case "sfixed32": out.writeSFixed32NoTag((int) value); break;
      case "enum": out.writeEnumNoTag((int) value); break;
      case "int64": out.writeInt64NoTag(value); break;
      case "uint64": out.writeUInt64NoTag(value); break;
      case "sint64": out.writeSInt64NoTag(value); break;
      case "fixed64": out.writeFixed64NoTag(value); break;
      case "sfixed64": out.writeSFixed64NoTag(value); break;
      case "float": out.writeFloatNoTag(Float.intBitsToFloat((int) value)); break;
      case "double": out.writeDoubleNoTag(Double.longBitsToDouble(value)); break;
      case "bool": out.writeBoolNoTag(value != 0); break;
      default: throw new IllegalArgumentException(kind);
    }
    out.flush();
    StringBuilder hex = new StringBuilder();
    for (byte b : bytes.toByteArray()) hex.append(String.format("%02x", b & 255));
    System.out.println("    \"" + kind + "|" + value + "|" + hex + "\",");
  }

  public static void main(String[] args) throws Exception {
    if (args.length != 1) throw new IllegalArgumentException("Expected protobuf-java version");
    System.out.println("package scalapb\n\n// Generated by sbt generateWireFixtures with protobuf-java " + args[0] + ".");
    System.out.println("// Do not edit by hand. Google runtime classes never enter the Scala test classpath.");
    System.out.println("// format: off\nobject WireFixtures {\n  val rows: Vector[String] = Vector(");
    Set<Long> ints = new LinkedHashSet<>();
    Set<Long> longs = new LinkedHashSet<>();
    for (long n : new long[] {0, -1, Integer.MIN_VALUE, Integer.MAX_VALUE}) ints.add(n);
    for (long n : new long[] {0, -1, Long.MIN_VALUE, Long.MAX_VALUE}) longs.add(n);
    for (int bit = 7; bit < 32; bit += 7)
      for (int delta = -1; delta <= 1; delta++) ints.add((1L << bit) + delta);
    for (int bit = 7; bit < 64; bit += 7)
      for (int delta = -1; delta <= 1; delta++) longs.add((1L << bit) + delta);
    Random random = new Random(0x5ca1ab);
    for (int i = 0; i < 16; i++) { ints.add((long) random.nextInt()); longs.add(random.nextLong()); }
    for (String kind : new String[] {"int32", "uint32", "sint32", "fixed32", "sfixed32", "enum"})
      for (long value : ints) emit(kind, value);
    for (String kind : new String[] {"int64", "uint64", "sint64", "fixed64", "sfixed64"})
      for (long value : longs) emit(kind, value);
    for (int bits : new int[] {0, 0x80000000, 1, 0x007fffff, 0x00800000, 0x7f7fffff, 0x7f800000, 0xff800000, 0x7fc00000}) emit("float", bits);
    for (long bits : new long[] {0, Long.MIN_VALUE, 1, 0x000fffffffffffffL, 0x0010000000000000L, 0x7fefffffffffffffL, 0x7ff0000000000000L, 0xfff0000000000000L, 0x7ff8000000000000L}) emit("double", bits);
    emit("bool", 0);
    emit("bool", 1);
    System.out.println("  )\n}\n// format: on");
  }
}
